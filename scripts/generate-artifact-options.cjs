// Generate the only flavor-dependent sources before build/pack. Stable packages
// contain no developer option names, native symbol references, or bridge parsing.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pkg = require(path.join(root, 'package.json'));
const dev = /^\d+\.\d+\.\d+-dev\.\d+$/.test(pkg.version);
const banner = `// Generated by scripts/generate-artifact-options.cjs. Artifact channel: ${dev ? 'development' : 'stable'}\n`;
const sources = {
  'src/internal/artifactOptions.ts': dev ? `
/** Only present in development SDK artifacts. Requires a process restart to change. */
export interface ArtifactInitOptions { hidePlayableCompanion?: boolean; }
export function normalizeArtifactOptions(config: ArtifactInitOptions): ArtifactInitOptions {
  return config.hidePlayableCompanion === true ? { hidePlayableCompanion: true } : {};
}
` : `
export interface ArtifactInitOptions {}
export function normalizeArtifactOptions(_config: ArtifactInitOptions): ArtifactInitOptions { return {}; }
`,
  'android/src/main/java/com/simulaads/reactnative/ArtifactOptions.kt': `
package com.simulaads.reactnative
import com.facebook.react.bridge.ReadableMap
import com.facebook.react.bridge.ReadableType
${dev ? 'import ad.simula.ad.sdk.ads.SimulaDevOptions' : ''}
internal fun configureArtifactOptions(config: ReadableMap): Boolean =
    ${dev ? 'SimulaDevOptions.configure(hidePlayableCompanion = runCatching { config.hasKey("hidePlayableCompanion") && config.getType("hidePlayableCompanion") == ReadableType.Boolean && config.getBoolean("hidePlayableCompanion") }.getOrDefault(false))' : 'true'}
`,
  'ios/ArtifactOptions.swift': `
import Foundation
${dev ? 'import SimulaAdSDK\nimport CoreFoundation' : ''}
func configureArtifactOptions(_ config: NSDictionary) -> Bool {
    ${dev ? `let value = config["hidePlayableCompanion"] as? NSNumber
    let hidden = value.map { CFGetTypeID($0) == CFBooleanGetTypeID() && $0.boolValue } ?? false
    return SimulaDevOptions.configure(hidePlayableCompanion: hidden)` : 'return true'}
}
`,
};
for (const [file, source] of Object.entries(sources)) {
  const target = path.join(root, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, banner + source.trimStart());
}
